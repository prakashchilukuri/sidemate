import { AIEmployeeFullConfig, SimulatedMessage } from "./types/ai-employee-builder";

export interface SimulationResult {
  reply: string;
  matchedFaq?: string;
  matchedObjection?: string;
  isEscalation: boolean;
  qualificationUpdated?: {
    questionId: string;
    questionText: string;
  };
  currentGoal: string;
  disclaimer: string;
}

export function generateSimulationResponse(
  config: AIEmployeeFullConfig,
  userMessage: string,
  history: SimulatedMessage[]
): SimulationResult {
  const lowerMsg = userMessage.toLowerCase().trim();
  const DISCLAIMER = "⚠️ Simulated Preview Only — Response generated by SideMate simulation engine based on your configured prompt, business rules, and knowledge base.";

  // 1. Escalation check
  const escalationTriggers = config.escalation?.triggers || ["human", "person", "representative", "manager", "support"];
  const matchedTrigger = escalationTriggers.find((trigger) => lowerMsg.includes(trigger.toLowerCase()));
  if (matchedTrigger) {
    const handoffMsg =
      config.escalation?.handoffMessage ||
      `I completely understand. Let me connect you directly with a member of our team at ${config.escalation?.escalationPhone || "+1 (555) 019-2834"}.`;
    return {
      reply: handoffMsg,
      isEscalation: true,
      currentGoal: "Escalate to Human Representative",
      disclaimer: DISCLAIMER,
    };
  }

  // 2. Objection check
  if (config.objectionHandlers && config.objectionHandlers.length > 0) {
    for (const handler of config.objectionHandlers) {
      const objectionWords = handler.objection.toLowerCase().split(/\s+/).filter((w) => w.length > 3);
      const matchesWord = objectionWords.some((w) => lowerMsg.includes(w));
      if (matchesWord || lowerMsg.includes(handler.objection.toLowerCase())) {
        return {
          reply: handler.response,
          matchedObjection: handler.objection,
          isEscalation: false,
          currentGoal: "Handle Prospect Hesitation",
          disclaimer: DISCLAIMER,
        };
      }
    }
  }

  // 3. FAQ check
  if (config.faqs && config.faqs.length > 0) {
    for (const faq of config.faqs) {
      const faqWords = faq.question.toLowerCase().split(/\s+/).filter((w) => w.length > 3);
      const matchCount = faqWords.filter((w) => lowerMsg.includes(w)).length;
      if (matchCount >= 2 || (faqWords.length <= 2 && matchCount >= 1)) {
        return {
          reply: `${faq.answer} Does that help answer your question?`,
          matchedFaq: faq.question,
          isEscalation: false,
          currentGoal: "Address Inbound FAQ",
          disclaimer: DISCLAIMER,
        };
      }
    }
  }

  // 4. Qualification Questions check
  const qualificationQuestions = config.qualificationQuestions || [];
  // Count how many qualification questions have already been discussed
  const userTurns = history.filter((h) => h.sender === "user").length;
  
  // If user provided substantive answer, mark question
  let qualificationUpdated: { questionId: string; questionText: string } | undefined;
  const currentQIndex = Math.min(userTurns, qualificationQuestions.length - 1);
  const currentQ = qualificationQuestions[currentQIndex];

  if (currentQ && userTurns > 0) {
    qualificationUpdated = {
      questionId: currentQ.id,
      questionText: currentQ.question,
    };
  }

  // Next qualification question to ask
  const nextQ = qualificationQuestions[currentQIndex + 1];

  // 5. Calendar / Booking intent
  if (
    lowerMsg.includes("book") ||
    lowerMsg.includes("demo") ||
    lowerMsg.includes("calendar") ||
    lowerMsg.includes("meet") ||
    lowerMsg.includes("call me") ||
    lowerMsg.includes("schedule")
  ) {
    const calendar = config.telephony?.calendarUrl || "https://calendly.com/discovery";
    return {
      reply: `Fantastic! I can lock in a 20-minute discovery call for you right away. You can also view available slots directly at ${calendar}. Would tomorrow morning or afternoon work better for your schedule?`,
      isEscalation: false,
      currentGoal: "Secure Scheduled Appointment",
      disclaimer: DISCLAIMER,
    };
  }

  // 6. Next progression according to primary task
  let progressionReply = "";
  const style = config.communicationStyle || "consultative";
  const business = config.businessName || "our company";

  if (nextQ) {
    const bridgePhrase =
      style === "friendly"
        ? "That makes total sense! To help me understand how we can best support you,"
        : style === "authoritative"
        ? "Understood. The critical factor for our evaluation is:"
        : "Got it, that's very helpful context. Quick question for you:";
    progressionReply = `${bridgePhrase} ${nextQ.question}`;
  } else {
    // All questions answered or no questions
    if (config.primaryTask === "appointment_booking" || config.primaryTask === "lead_qualification") {
      progressionReply = `Based on what you've shared, ${business} seems like a great fit for your requirements. Would you be open to a quick 15-minute walkthrough with our solution engineering team this week?`;
    } else if (config.primaryTask === "customer_support") {
      progressionReply = `Thank you for confirming. I have logged this against your ${business} account. Is there anything else I can assist you with today?`;
    } else {
      progressionReply = `Thank you for sharing that. Here at ${business}, our mission is to ensure you achieve maximum ROI with minimal ramp-up time. Would you like me to send over our executive summary?`;
    }
  }

  return {
    reply: progressionReply,
    isEscalation: false,
    qualificationUpdated,
    currentGoal: nextQ ? `Qualify Criteria: ${nextQ.criteria}` : "Finalize Next Steps",
    disclaimer: DISCLAIMER,
  };
}

/**
 * Compiles all builder sections into a cohesive production system prompt
 */
export function compileSystemPrompt(config: AIEmployeeFullConfig): string {
  const parts: string[] = [];

  parts.push(`=== IDENTITY & ROLE ===`);
  parts.push(`You are ${config.name}, working as ${config.role} at ${config.businessName}.`);
  parts.push(`Company Profile: ${config.businessDescription}`);
  parts.push(`Primary Directive: ${config.primaryTask.replace(/_/g, " ").toUpperCase()}`);
  parts.push(`Language: ${config.language}`);
  parts.push(`Communication Style: ${config.communicationStyle} (Tone: ${config.tone})`);
  parts.push("");

  parts.push(`=== SYSTEM INSTRUCTIONS ===`);
  parts.push(config.systemInstructions);
  parts.push("");

  if (config.greeting) {
    parts.push(`=== INITIAL GREETING ===`);
    parts.push(`When call connects, immediately state: "${config.greeting}"`);
    parts.push("");
  }

  if (config.conversationGoals && config.conversationGoals.length > 0) {
    parts.push(`=== CONVERSATION GOALS ===`);
    config.conversationGoals.forEach((goal, i) => {
      parts.push(`${i + 1}. ${goal}`);
    });
    parts.push("");
  }

  if (config.qualificationQuestions && config.qualificationQuestions.length > 0) {
    parts.push(`=== QUALIFICATION CHECKLIST ===`);
    config.qualificationQuestions.forEach((q, i) => {
      parts.push(`${i + 1}. [${q.required ? "REQUIRED" : "OPTIONAL"}] Question: "${q.question}" -> Target Criteria: ${q.criteria}`);
    });
    parts.push("");
  }

  if (config.objectionHandlers && config.objectionHandlers.length > 0) {
    parts.push(`=== OBJECTION PLAYBOOK ===`);
    config.objectionHandlers.forEach((obj, i) => {
      parts.push(`Objection ${i + 1}: If lead says "${obj.objection}" -> Respond: "${obj.response}"`);
    });
    parts.push("");
  }

  if (config.faqs && config.faqs.length > 0) {
    parts.push(`=== FREQUENTLY ASKED QUESTIONS ===`);
    config.faqs.forEach((faq, i) => {
      parts.push(`Q${i + 1}: ${faq.question}`);
      parts.push(`A${i + 1}: ${faq.answer}`);
    });
    parts.push("");
  }

  if (config.knowledgeSources && config.knowledgeSources.length > 0) {
    parts.push(`=== KNOWLEDGE BASE SOURCES ===`);
    config.knowledgeSources.forEach((src, i) => {
      parts.push(`[Source ${i + 1}: ${src.title} (${src.type})]`);
      parts.push(src.content);
    });
    parts.push("");
  }

  parts.push(`=== OPERATING HOURS & ESCALATION ===`);
  parts.push(`Timezone: ${config.businessHours?.timezone || "America/New_York"}`);
  parts.push(`Hours: ${config.businessHours?.startTime} - ${config.businessHours?.endTime}`);
  parts.push(`Active Days: ${(config.businessHours?.days || []).join(", ")}`);
  parts.push(`Escalation Transfer Phone: ${config.escalation?.escalationPhone}`);
  parts.push(`Escalation Transfer Email: ${config.escalation?.escalationEmail}`);
  parts.push(`Escalation Triggers: ${(config.escalation?.triggers || []).join(", ")}`);
  parts.push(`Handoff Message: "${config.escalation?.handoffMessage}"`);
  parts.push("");

  parts.push(`=== VOICE & TELEPHONY TELEMETRY ===`);
  parts.push(`Voice Model: ${config.telephony?.voiceId}`);
  parts.push(`Speech Pace: ${config.telephony?.speed}x`);
  parts.push(`Ambient Audio: ${config.telephony?.ambientNoise}`);
  parts.push(`Caller ID: ${config.telephony?.callerId}`);
  parts.push(`Max Call Duration: ${config.telephony?.maxDurationMinutes} minutes`);
  if (config.telephony?.calendarUrl) {
    parts.push(`Calendar Booking Link: ${config.telephony?.calendarUrl}`);
  }

  return parts.join("\n");
}

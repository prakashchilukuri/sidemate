// Simulation Engine Test Implementation
function testSimulateResponse(config, userMessage, history) {
  const lowerMsg = userMessage.toLowerCase().trim();
  const DISCLAIMER = "⚠️ Simulated Preview Only — Response generated by SideMate simulation engine.";

  // Escalation
  const triggers = config.escalation?.triggers || ["human", "representative"];
  if (triggers.some((t) => lowerMsg.includes(t.toLowerCase()))) {
    return {
      reply: config.escalation.handoffMessage,
      isEscalation: true,
      disclaimer: DISCLAIMER,
    };
  }

  // Objection
  if (config.objectionHandlers) {
    for (const obj of config.objectionHandlers) {
      if (lowerMsg.includes(obj.objection.toLowerCase())) {
        return {
          reply: obj.response,
          matchedObjection: obj.objection,
          isEscalation: false,
          disclaimer: DISCLAIMER,
        };
      }
    }
  }

  // FAQ
  if (config.faqs) {
    for (const faq of config.faqs) {
      if (lowerMsg.includes("price") || lowerMsg.includes("cost") || lowerMsg.includes(faq.question.toLowerCase())) {
        return {
          reply: faq.answer,
          matchedFaq: faq.question,
          isEscalation: false,
          disclaimer: DISCLAIMER,
        };
      }
    }
  }

  return {
    reply: "Thank you for that context. Let's look into how we can assist your workflow.",
    isEscalation: false,
    disclaimer: DISCLAIMER,
  };
}

